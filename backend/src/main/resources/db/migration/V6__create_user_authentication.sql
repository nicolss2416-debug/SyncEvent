CREATE TABLE user_accounts (
    id UUID PRIMARY KEY,
    email VARCHAR(254) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    active BOOLEAN NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    CONSTRAINT uk_user_accounts_email UNIQUE (email)
);

CREATE TABLE user_account_roles (
    user_id UUID NOT NULL REFERENCES user_accounts(id),
    role VARCHAR(30) NOT NULL,
    PRIMARY KEY (user_id, role),
    CONSTRAINT ck_user_account_roles_role
        CHECK (role IN ('ADMINISTRADOR', 'OPERADOR', 'MONITOR', 'INVITADO'))
);

CREATE TABLE auth_sessions (
    id UUID PRIMARY KEY,
    user_id UUID NOT NULL REFERENCES user_accounts(id),
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    last_activity_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    revoked_at TIMESTAMP WITHOUT TIME ZONE
);

CREATE INDEX idx_auth_sessions_user_active
    ON auth_sessions (user_id, last_activity_at)
    WHERE revoked_at IS NULL;

CREATE TABLE auth_activity (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id UUID REFERENCES user_accounts(id),
    email VARCHAR(254) NOT NULL,
    activity VARCHAR(30) NOT NULL,
    occurred_at TIMESTAMP WITHOUT TIME ZONE NOT NULL
);

CREATE INDEX idx_auth_activity_email_occurred
    ON auth_activity (email, occurred_at);
