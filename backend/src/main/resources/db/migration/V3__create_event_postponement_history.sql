CREATE TABLE event_postponement_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    event_id UUID NOT NULL REFERENCES events(id),
    action VARCHAR(30) NOT NULL,
    previous_start_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    previous_end_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    new_start_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    new_end_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    reason VARCHAR(2000) NOT NULL,
    recorded_at TIMESTAMP WITHOUT TIME ZONE NOT NULL
);

CREATE INDEX idx_event_postponement_history_event_id
    ON event_postponement_history (event_id, id);
