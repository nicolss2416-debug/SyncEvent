CREATE TABLE audit_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    occurred_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    user_id UUID REFERENCES user_accounts(id) ON DELETE SET NULL,
    user_email VARCHAR(254) NOT NULL,
    action VARCHAR(80) NOT NULL,
    entity_type VARCHAR(40) NOT NULL,
    entity_id VARCHAR(120),
    ip_address VARCHAR(45),
    result VARCHAR(20) NOT NULL,
    reason VARCHAR(2000),
    details VARCHAR(1000),
    http_method VARCHAR(10),
    http_path VARCHAR(500),
    status_code INTEGER
);

CREATE INDEX idx_audit_log_occurred ON audit_log (occurred_at DESC);
CREATE INDEX idx_audit_log_user_email ON audit_log (user_email);
CREATE INDEX idx_audit_log_entity ON audit_log (entity_type, entity_id);
CREATE INDEX idx_audit_log_action ON audit_log (action);
CREATE INDEX idx_audit_log_result ON audit_log (result, occurred_at DESC);

-- Los registros de auditoría son inalterables: se impide modificarlos o eliminarlos.
CREATE OR REPLACE FUNCTION prevent_audit_log_mutation()
RETURNS TRIGGER AS $$
BEGIN
    RAISE EXCEPTION 'Los registros de auditoría son inalterables';
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trg_audit_log_immutable
    BEFORE UPDATE OR DELETE ON audit_log
    FOR EACH ROW
    EXECUTE FUNCTION prevent_audit_log_mutation();

-- Importa la actividad histórica real de autenticación y administración de cuentas.
INSERT INTO audit_log (
    occurred_at, user_id, user_email, action, entity_type, entity_id,
    ip_address, result, reason, details, http_method, http_path, status_code)
SELECT
    activity.occurred_at,
    activity.user_id,
    activity.email,
    activity.activity,
    CASE
        WHEN activity.activity IN ('MONITOR_ASSIGNED', 'MONITOR_REMOVED') THEN 'EVENTO'
        WHEN activity.activity = 'REGISTRATION_CREATED' THEN 'INSCRIPCION'
        WHEN activity.activity IN (
            'LOGIN_SUCCESS', 'LOGIN_FAILED', 'REGISTER', 'LOGOUT', 'ADMIN_BOOTSTRAP',
            'ADMIN_USER_CREATED', 'ADMIN_USER_UPDATED', 'USER_ROLE_ADDED', 'USER_ACTIVATED',
            'USER_DEACTIVATED', 'PARTICIPANT_LINKED', 'PARTICIPANT_PROFILE_COMPLETED') THEN 'USUARIO'
        ELSE 'SISTEMA'
    END,
    NULL,
    NULL,
    CASE WHEN activity.activity = 'LOGIN_FAILED' THEN 'FALLO' ELSE 'EXITO' END,
    NULL,
    'Registro histórico importado desde auth_activity',
    CASE WHEN activity.activity LIKE 'LOGIN%' OR activity.activity IN ('LOGOUT', 'REGISTER') THEN 'POST' END,
    NULL,
    NULL
FROM auth_activity activity;

-- Importa las cancelaciones de inscripción históricas (actor y motivo reales).
INSERT INTO audit_log (
    occurred_at, user_id, user_email, action, entity_type, entity_id,
    ip_address, result, reason, details, http_method, http_path, status_code)
SELECT
    cancellation.canceled_at,
    cancellation.canceled_by,
    COALESCE(account.email, 'desconocido'),
    'INSCRIPCION_CANCELADA',
    'INSCRIPCION',
    cancellation.registration_id::text,
    NULL,
    'EXITO',
    cancellation.reason,
    'Registro histórico importado desde registration_cancellation_history',
    'POST',
    NULL,
    NULL
FROM registration_cancellation_history cancellation
LEFT JOIN user_accounts account ON account.id = cancellation.canceled_by;
